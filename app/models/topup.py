from datetime import datetime
from enum import Enum
from uuid import UUID, uuid4

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    Enum as SQLEnum,
    ForeignKey,
    String,
    Uuid,
    UniqueConstraint,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.database import Base
from app.core.enums import Currency


class TopUpStatus(str, Enum):
    """Nexa funding states used by TopUp, the processor, and API responses.

    These describe our wallet funding progress, not Moyasar's payment status.
    """

    PENDING = "PENDING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    # A discrepancy needs investigation before crediting the wallet, such as an amount mismatch.
    REVIEW_REQUIRED = "REVIEW_REQUIRED"


class TopUp(Base):
    """Database model for one request to fund a Nexa wallet.

    Source: TopUpService creates it from an authenticated POST /topups request.
    Use: the mobile receives payment details; the processor verifies payment
    against this record and links transaction_id after posting the wallet credit.
    Creating this record alone does not change the wallet balance.
    Internal wallet transfers do not create a TopUp.
    """

    __tablename__ = "topups"

    __table_args__ = (
        UniqueConstraint("user_id", "idempotency_key", name="uq_topup_user_key"),
        CheckConstraint(
            "amount_minor > 0",
            name="ck_topup_amount_positive",
        ),
    )

    # Generated by Nexa; the mobile uses it in GET /topups/{topup_id}.
    id: Mapped[UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid4,
    )

    # Comes from the authenticated user; used for ownership checks.
    user_id: Mapped[int] = mapped_column(
        ForeignKey("users.id"),
        nullable=False,
    )

    # One key per user's funding request. NULL is only for records created before migration.
    idempotency_key: Mapped[str | None] = mapped_column(String(128), nullable=True)

    # Selected by the mobile and checked by the service; receives the credit.
    wallet_id: Mapped[int] = mapped_column(
        ForeignKey("wallets.id"),
        nullable=False,
    )
    # Amount in minor units: for example, 100 AED = 10000 fils.
    # Store an integer to preserve precision.
    amount_minor: Mapped[int] = mapped_column(
        BigInteger,
        nullable=False,
    )

    # Copied from the wallet; compared with the payment returned by Moyasar.
    currency: Mapped[Currency] = mapped_column(
        SQLEnum(Currency, name="currency"),
        nullable=False,
    )

    # Generated by Nexa and passed to the SDK as givenID; links payment to TopUp.
    moyasar_payment_id: Mapped[str] = mapped_column(
        String(36),
        unique=True,
        nullable=False,
        default=lambda: str(uuid4()),
    )

    # Empty before posting; the processor links the created financial transaction.
    transaction_id: Mapped[int | None] = mapped_column(
        ForeignKey("transactions.id"),
        unique=True,
        nullable=True,
    )

    # Starts PENDING; the processor updates it, and the mobile reads it via the API.
    status: Mapped[TopUpStatus] = mapped_column(
        SQLEnum(TopUpStatus, name="topup_status"),
        default=TopUpStatus.PENDING,
        nullable=False,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )
